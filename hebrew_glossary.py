def main():
    PAGE = pathlib.Path(__file__).resolve().parent / "index.html"
    s = PAGE.read_text(encoding="utf-8")

    m = re.search(r'(<script id="explaindata" type="application/json">)(.*?)(</script>)', s, re.S)
    assert m, "explaindata blob not found"
    data = json.loads(m.group(2).replace("<\\/", "</"))
    gloss = data["glossary"]

    # every term must be covered, and nothing invented
    have = {e["t"] for e in gloss}
    missing = sorted(have - set(G))
    extra = sorted(set(G) - have)
    if missing or extra:
        if missing:
            print("NOT TRANSLATED (%d):" % len(missing))
            for t in missing:
                print("   ", t)
        if extra:
            print("INVENTED — no such term (%d):" % len(extra))
            for t in extra:
                print("   ", t)
        sys.exit(1)

    heb = re.compile(r"[֐-׿]")
    for e in gloss:
        d = G[e["t"]]
        assert heb.search(d), "not Hebrew: " + e["t"]
        assert len(d) >= 25, "too thin: " + e["t"]
        e["d"] = d

    blob = json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    s = s[:m.start()] + m.group(1) + blob + m.group(3) + s[m.end():]

    # round-trip the page's own blob to prove it still parses
    chk = re.search(r'<script id="explaindata" type="application/json">(.*?)</script>', s, re.S)
    back = json.loads(chk.group(1).replace("<\\/", "</"))
    assert len(back["glossary"]) == 154 and len(back["cues"]) == len(data["cues"])
    assert all(heb.search(e["d"]) for e in back["glossary"])

    PAGE.write_text(s, encoding="utf-8")
    print("glossary translated · 154 terms · page %.2f MB" % (len(s) / 1e6))


if __name__ == "__main__":
    main()
